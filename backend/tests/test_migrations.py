import pytest
from alembic import command
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Engine

from app.prestart import alembic_config


def test_models_match_migrations(engine: Engine) -> None:
    with engine.connect() as connection:
        config = alembic_config()
        config.attributes["connection"] = connection
        command.check(config)


def test_check_detects_drift(engine: Engine) -> None:
    with engine.connect() as connection:
        transaction = connection.begin()
        connection.exec_driver_sql("ALTER TABLE users ADD COLUMN nickname text")
        config = alembic_config()
        config.attributes["connection"] = connection
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(config)
        transaction.rollback()


def test_downgrade_then_upgrade(engine: Engine) -> None:
    with engine.begin() as connection:
        config = alembic_config()
        config.attributes["connection"] = connection
        command.downgrade(config, "base")
        command.upgrade(config, "head")
