import pytest
from alembic import command
from alembic.util import AutogenerateDiffsDetected
from sqlalchemy import Engine

from app.prestart import alembic_config


def test_models_match_migrations(engine: Engine) -> None:
    with engine.connect() as connection:
        config = alembic_config()
        config.attributes["connection"] = connection
        command.check(config)


def test_check_detects_drift(engine: Engine) -> None:
    with engine.connect() as connection:
        transaction = connection.begin()
        connection.exec_driver_sql("ALTER TABLE users ADD COLUMN nickname text")
        config = alembic_config()
        config.attributes["connection"] = connection
        with pytest.raises(AutogenerateDiffsDetected):
            command.check(config)
        transaction.rollback()


def test_downgrade_then_upgrade(engine: Engine) -> None:
    with engine.begin() as connection:
        config = alembic_config()
        config.attributes["connection"] = connection
        command.downgrade(config, "base")
        command.upgrade(config, "head")


def test_barca_data_migration_splits_and_merges_back(engine: Engine) -> None:
    def rows() -> list[tuple]:
        return connection.exec_driver_sql(
            "SELECT user_id, topic, weight, created_at FROM interests ORDER BY user_id, id"
        ).all()

    def add_user(email: str) -> int:
        sql = f"INSERT INTO users (email, name) VALUES ('{email}', 'Fan') RETURNING id"
        return connection.exec_driver_sql(sql).scalar_one()

    with engine.connect() as connection:
        transaction = connection.begin()
        config = alembic_config()
        config.attributes["connection"] = connection
        command.downgrade(config, "e3d606ed94cd")
        fan = add_user("fan@example.com")
        connection.exec_driver_sql(
            "INSERT INTO interests (user_id, kind, topic, weight) VALUES "
            f"({fan}, 'catalog', 'fc-barcelona', 'high'), ({fan}, 'catalog', 'nba', 'low')"
        )
        joined = rows()[0][3]

        command.upgrade(config, "b07edd4c08e6")

        after = rows()
        assert [row[:3] for row in after] == [
            (fan, "fc-barcelona-football", "high"),
            (fan, "nba", "low"),
            (fan, "fc-barcelona-basketball", "high"),
        ]
        assert after[0][3] == after[2][3] == joined
        hoops = add_user("hoops@example.com")
        connection.exec_driver_sql(
            "INSERT INTO interests (user_id, kind, topic, weight) VALUES "
            f"({hoops}, 'catalog', 'fc-barcelona-basketball', 'medium')"
        )

        command.downgrade(config, "e3d606ed94cd")

        assert [row[:3] for row in rows()] == [
            (fan, "fc-barcelona", "high"),
            (fan, "nba", "low"),
            (hoops, "fc-barcelona", "medium"),
        ]
        transaction.rollback()


def test_tone_voice_rows_leave_provider_calls_only(engine: Engine) -> None:
    def rows() -> list[tuple]:
        return connection.exec_driver_sql(
            "SELECT e.status, s.stage, s.details, c.model, c.characters FROM episodes e "
            "JOIN stage_runs s ON s.episode_id = e.id "
            "LEFT JOIN provider_calls c ON c.stage_run_id = s.id ORDER BY c.id"
        ).all()

    with engine.connect() as connection:
        transaction = connection.begin()
        config = alembic_config()
        config.attributes["connection"] = connection
        command.downgrade(config, "a5739803b67f")
        user = connection.exec_driver_sql(
            "INSERT INTO users (email, name) VALUES ('fan@example.com', 'Fan') RETURNING id"
        ).scalar_one()
        episode = connection.exec_driver_sql(
            "INSERT INTO episodes (user_id, trigger, scheduled_for, status, status_reason) "
            f"VALUES ({user}, 'manual', now(), 'failed', 'master: loudness') RETURNING id"
        ).scalar_one()
        stage = connection.exec_driver_sql(
            "INSERT INTO stage_runs (episode_id, attempt, stage, status, details) VALUES "
            f"({episode}, 1, 'voice', 'completed', '{{\"requests\": [{{\"chars\": 90}}]}}') "
            "RETURNING id"
        ).scalar_one()
        connection.exec_driver_sql(
            "INSERT INTO provider_calls "
            "(stage_run_id, provider, model, characters, cost_usd, latency_ms) VALUES "
            f"({stage}, 'elevenlabs', 'tone-for-development', 90, 0, 0), "
            f"({stage}, 'elevenlabs', 'eleven_v3', 60, 0.006, 900)"
        )

        command.upgrade(config, "a44ca396f657")

        kept = [("failed", "voice", {"requests": [{"chars": 90}]}, "eleven_v3", 60)]
        assert rows() == kept
        command.downgrade(config, "a5739803b67f")
        assert rows() == kept
        transaction.rollback()
